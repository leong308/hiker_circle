"""Generate the allowlisted mobile asset. Never copy private provider keys.

Run before flutter pub get/build. Environment values take precedence over .env.
"""
import os
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def local_values():
    values = {}
    source = ROOT / '.env'
    if source.exists():
        for line in source.read_text(encoding='utf-8-sig').splitlines():
            key, sep, value = line.partition('=')
            if sep and not key.strip().startswith('#'):
                values[key.strip()] = value.strip().strip('\"\'')
    return values


if __name__ == '__main__':
    values = local_values()
    token = os.environ.get('MAPBOX_ACCESS_TOKEN', values.get('MAPBOX_ACCESS_TOKEN', '')).strip()
    if token and (not token.startswith('pk.') or '\n' in token or '\r' in token):
        raise SystemExit('MAPBOX_ACCESS_TOKEN must be a public pk token.')
    enabled = os.environ.get('OPENWEATHER_TILES_ENABLED', 'false').lower() == 'true'
    (ROOT / '.env.public').write_text(
        '# Public mobile configuration only. Generated by scripts/prepare_mobile_public_config.py\n'
        f'MAPBOX_ACCESS_TOKEN={token}\nOPENWEATHER_TILES_ENABLED={str(enabled).lower()}\n',
        encoding='utf-8',
    )
    print('Generated mobile public configuration (private values excluded).')
